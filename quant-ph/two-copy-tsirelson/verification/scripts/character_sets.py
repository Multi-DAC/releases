# The four sets of Theorem 2 from the paper's own definitions (Section 3), and the facts about them that the
# paper states: M_k = +-4 on every point (Lemma 9), |S_k| = 128, the character form agrees with the
# relabellings of Remark 3 point by point, the relabelling group has order 64 and S_0 has exactly four images,
# and the pointwise identity sum_k 1_{S_k} = 2 - C1 C2 / 4. Also: 256 events, 22,400 locally orthogonal
# pairs, 175 per event, and dim W = 81 by exact integer rank.
# Points and events are built in base.py: party j = 0..3 is A1, B1, A2, B2; value 0 <-> outcome +1.
import os, sys, itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import flint
from base import NP, NE, EVENTS, ALPHA, EV_IND, ORTH, ORTH_PAIRS, C_func, val

# ---- Section 3: m_s, phi, the characters, M_k, S_k
def m(s):
    x, y, xp, yp = s
    return ALPHA[:, 0, x] * ALPHA[:, 1, y] * ALPHA[:, 2, xp] * ALPHA[:, 3, yp]

def phi(s):
    x, y, xp, yp = s
    return (x + x * xp + x * yp + y * yp) % 2

CHI = [lambda s: 1,
       lambda s: (-1) ** ((s[1] + s[2] + s[3]) % 2),
       lambda s: (-1) ** ((s[0] + s[3]) % 2),
       lambda s: (-1) ** ((s[0] + s[1] + s[2]) % 2)]
C = [1, -1, 1, 1]
F2_4 = list(itertools.product(range(2), repeat=4))
M = [C[k] * sum((-1) ** phi(s) * CHI[k](s) * m(s) for s in F2_4) for k in range(4)]
for k in range(4):
    print("M_%d takes values %s" % (k, sorted(set(M[k].tolist()))))
S = [M[k] == -4 for k in range(4)]
print("|S_k| =", [int(x.sum()) for x in S])

# ---- Remark 3: tau_j swaps the two boxes of party j and flips the outcome of box 1 of its partner in the same copy
def tau(j):
    p = j ^ 1
    out = np.zeros(NP, dtype=np.int64)
    for w in range(NP):
        nw = 0
        for i in range(4):
            for b in range(2):
                v = val(w, i, 1 - b) if i == j else val(w, i, b)
                if i == p and b == 1:
                    v ^= 1
                nw |= v << (2 * i + b)
        out[w] = nw
    return out

T = {name: tau(j) for j, name in enumerate(["A1", "B1", "A2", "B2"])}
for name, t in T.items():
    assert np.array_equal(t[t], np.arange(NP)), "tau is not an involution"
claims = [(1, "A1"), (2, "B1"), (2, "A2"), (3, "B2")]
for k, name in claims:
    same = np.array_equal(M[k], M[0][T[name]])
    print("M_%d == M_0 o tau_%s on all 256 points: %s" % (k, name, same))
    print("   S_%d == tau_%s(S_0) as point sets: %s" % (k, name,
          set(np.flatnonzero(S[k]).tolist()) == set(T[name][np.flatnonzero(S[0])].tolist())))
# control: a wrong assignment must fail
print("control, M_1 == M_0 o tau_B2 (expected False):", np.array_equal(M[1], M[0][T["B2"]]))

# group generated by the four tau_j, as permutations of the points; images of S_0
gens = [tuple(t.tolist()) for t in T.values()]
ident = tuple(range(NP))
group = {ident}
frontier = [ident]
while frontier:
    new = []
    for g in frontier:
        for t in gens:
            h = tuple(t[i] for i in g)
            if h not in group:
                group.add(h)
                new.append(h)
    frontier = new
print("order of the group generated by the four tau_j:", len(group))
S0 = np.flatnonzero(S[0])
images = {frozenset(g[i] for i in S0) for g in group}
print("distinct images of S_0 under it:", len(images))
print("they are exactly S_0..S_3:", images == {frozenset(np.flatnonzero(x).tolist()) for x in S})

# pointwise identity and Lemma 9's sign sum
C1, C2 = C_func(0), C_func(1)
lhs = sum(x.astype(np.int64) for x in S)
print("4 * sum_k 1_{S_k} == 8 - C1 C2 on all 256 points:", np.array_equal(4 * lhs, 8 - C1 * C2))
ok = all(sum(C[k] * CHI[k](s) for k in range(4)) == 2 * (-1) ** (((s[0] + s[3]) * (s[0] + s[1] + s[2])) % 2)
         for s in F2_4)
print("sum_k c_k chi_k(s) == 2 (-1)^{ab}, a = x + y', b = x + y + x', for all 16 s:", ok)
ok = all((phi(s) + (s[0] + s[3]) * (s[0] + s[1] + s[2])) % 2 == (s[0] * s[1] + s[2] * s[3]) % 2 for s in F2_4)
print("phi(s) + ab == xy + x'y' mod 2 for all 16 s:", ok)

# ---- Section 2: counts and dim W (exact)
print("events:", NE, "; locally orthogonal pairs:", len(ORTH_PAIRS),
      "; orthogonal partners per event:", sorted(set(ORTH.sum(axis=1).tolist())))
